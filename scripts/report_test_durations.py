"""Report pytest JUnit XML durations, individually and summed over parametrizations.

Usage:

`python scripts/report_test_durations.py test-results.xml`

This script is used in `tests.yml`.

Set `TEST_DURATION_TOP_K` to a positive integer to override the default of 10.
"""

import argparse
import math
import os
import xml.etree.ElementTree as ET
from collections import Counter, defaultdict


def report_individual(durations, top_k):
    print("#" * 50)
    print(f"\nTop {top_k} slowest individual tests:")
    for (classname, name), duration in sorted(durations.items(), key=lambda item: (-item[1], item[0]))[:top_k]:
        test = f"{classname}::{name}" if classname else name
        print(f"{duration:10.2f}s  {test}")


def report_aggregate(durations, top_k):
    aggregate = defaultdict(float)
    counts = Counter()
    for (classname, name), duration in durations.items():
        key = (classname, name.partition("[")[0])
        aggregate[key] += duration
        counts[key] += 1

    print("#" * 50)
    print(f"\nTop {top_k} slowest tests summed over parametrizations:")
    for (classname, name), duration in sorted(aggregate.items(), key=lambda item: (-item[1], item[0]))[:top_k]:
        test = f"{classname}::{name}" if classname else name
        print(f"{duration:10.2f}s  {counts[(classname, name)]:5d} cases  {test}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("report", help="JUnit XML report generated by pytest --junitxml")
    args = parser.parse_args()

    try:
        top_k = int(os.environ.get("TEST_DURATION_TOP_K", "10"))
    except ValueError:
        parser.error("TEST_DURATION_TOP_K must be a positive integer.")
    if top_k < 1:
        parser.error(f"TEST_DURATION_TOP_K must be a positive integer, got {top_k} instaed.")

    durations = defaultdict(float)
    try:
        for case in ET.parse(args.report).iter("testcase"):
            duration = float(case.get("time", "0"))
            if not math.isfinite(duration) or duration < 0:
                raise ValueError(f"invalid test duration: {duration}")
            # A call failure followed by a teardown failure can produce two entries for the same test.
            durations[(case.get("classname", ""), case.attrib["name"])] += duration
    except (OSError, ET.ParseError, KeyError, ValueError) as exc:
        parser.error(f"Cannot read test durations from {args.report}: {exc}")

    if not durations:
        print("No test durations found in the report.")
        return

    print("Durations include setup and teardown; sums across workers are not elapsed job time.")
    report_individual(durations, top_k)
    report_aggregate(durations, top_k)


if __name__ == "__main__":
    main()
